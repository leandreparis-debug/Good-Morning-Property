/**
 * Prepares the background photo (public/images/background-hills.jpg).
 *
 * - Always: regenerates the tiny blurred placeholder in src/lib/backgroundBlur.ts.
 * - Only if the source exceeds 600 KB: re-encodes it to AVIF, WebP and JPEG,
 *   at 2400 px (desktop / projection) and 1200 px (mobile).
 *
 * Usage: pnpm optimize:background
 */
import { stat, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const ROOT = path.resolve(import.meta.dirname, "..");
const SOURCE = path.join(ROOT, "public/images/background-hills.jpg");
const BLUR_FILE = path.join(ROOT, "src/lib/backgroundBlur.ts");
const MAX_BYTES = 600 * 1024;
const WIDTHS = [2400, 1200] as const;

async function writeBlurPlaceholder(): Promise<void> {
  const buffer = await sharp(SOURCE).resize(24).webp({ quality: 50 }).toBuffer();
  const dataUrl = `data:image/webp;base64,${buffer.toString("base64")}`;
  await writeFile(
    BLUR_FILE,
    "// Generated by scripts/optimize-background.ts. Do not edit by hand.\n" +
      `export const BACKGROUND_BLUR_DATA_URL =\n  "${dataUrl}";\n`,
  );
  process.stdout.write(`Blur placeholder written (${buffer.length} B).\n`);
}

async function reencode(): Promise<void> {
  for (const width of WIDTHS) {
    const base = path.join(ROOT, `public/images/background-hills-${width}`);
    const pipeline = sharp(SOURCE).resize({ width, withoutEnlargement: true });
    await pipeline.clone().avif({ quality: 55 }).toFile(`${base}.avif`);
    await pipeline.clone().webp({ quality: 72 }).toFile(`${base}.webp`);
    await pipeline
      .clone()
      .jpeg({ quality: 78, mozjpeg: true, progressive: true })
      .toFile(`${base}.jpg`);
    process.stdout.write(`Encoded ${path.basename(base)}.{avif,webp,jpg}\n`);
  }
}

async function main(): Promise<void> {
  const { size } = await stat(SOURCE);
  const { width, height } = await sharp(SOURCE).metadata();
  process.stdout.write(`Source: ${width}x${height}, ${Math.round(size / 1024)} KB\n`);

  await writeBlurPlaceholder();

  if (size > MAX_BYTES) {
    await reencode();
  } else {
    process.stdout.write(
      "Under 600 KB: no re-encoding (next/image serves AVIF/WebP per device).\n",
    );
  }
}

main().catch((error: unknown) => {
  process.stderr.write(`${String(error)}\n`);
  process.exit(1);
});
